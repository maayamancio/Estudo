# Variáveis e tipos de dados "básicos"
# Uma variável é um espaço na memória do computador onde podemos armazenar um valor.

nome = "Mayara" # String (texto)
idade = 30 # var do tipo Inteiro (número inteiro)
altura = 1.65 # var do tipo Float (número decimal)
Engenheira = True # var do tipo Booleano (verdadeiro ou falso)

print(f"Nome: {nome}, Idade: {idade}, Altura: {altura}, Engenheira: {Engenheira}")    